#!/usr/bin/env python3
"""Round-3 at-scale corpus: 160 notes, ~800k chars — the '24-frame archive'
scale claimed as docs mode's niche (a ~200k-text-token corpus).

Three seeded concepts (overrun 7, corrosion 5, wildlife 6) hidden across 160
notes with decoys, exact-set scoring. Reuses round 2's sentence pools and
concept phrasings; separate seed, separate output dir — round 2's corpus/
stays byte-identical.

Run: python3 gen_corpus3.py  -> writes corpus3/notes/*.md, prints ground truth.
"""
import random
from pathlib import Path

from gen_corpus import (OVERRUN, CORROSION, DECOYS, WEATHER, OPS,
                        PERSONNEL, SUPPLY)

OUT = Path(__file__).resolve().parent / "corpus3"
N_NOTES = 160
rng = random.Random(333_2026_0728)

WILDLIFE = [
    "A skua made off with the anemometer cups during the morning round; wind data has a gap until the spares went up.",
    "Penguins took up residence inside the boat shed and had to be evicted before slipway work could continue.",
    "A leopard seal punctured the inflatable's pontoon at the landing and the boat is out of service for patching.",
    "An arctic fox chewed clean through the seismometer cable overnight, and the instrument dropped off the network.",
    "Nesting gulls fouled the solar array badly enough to halve its output until the panels were washed down.",
    "An elephant seal hauled out across the tide-gauge housing and flattened it; readings stopped until the rebuild.",
]
WILDLIFE_DECOYS = [
    "The monthly wildlife census recorded normal skua and petrel numbers around the point.",
    "A seal hauled out near the jetty for most of the afternoon but caused no trouble.",
    "Bird activity around the station was unremarkable this week, per the observer's log.",
]

def build():
    all_decoys = DECOYS + WILDLIFE_DECOYS
    ids = [f"note-{i:03d}" for i in range(1, N_NOTES + 1)]
    special = rng.sample(ids, len(OVERRUN) + len(CORROSION) + len(WILDLIFE)
                         + len(all_decoys))
    i0 = len(OVERRUN)
    i1 = i0 + len(CORROSION)
    i2 = i1 + len(WILDLIFE)
    overrun_ids = sorted(special[:i0])
    corrosion_ids = sorted(special[i0:i1])
    wildlife_ids = sorted(special[i1:i2])
    decoy_ids = special[i2:]
    inserts = {}
    for nid, s in zip(overrun_ids, rng.sample(OVERRUN, len(OVERRUN))):
        inserts[nid] = s
    for nid, s in zip(corrosion_ids, rng.sample(CORROSION, len(CORROSION))):
        inserts[nid] = s
    for nid, s in zip(wildlife_ids, rng.sample(WILDLIFE, len(WILDLIFE))):
        inserts[nid] = s
    for nid, s in zip(decoy_ids, rng.sample(all_decoys, len(all_decoys))):
        inserts[nid] = s

    outdir = OUT / "notes"
    outdir.mkdir(parents=True, exist_ok=True)
    total = 0
    for i, nid in enumerate(ids):
        paras = [f"# {nid}: Station operations log, week {i + 1}\n"]
        for pool, label in [(WEATHER, "Weather"), (OPS, "Operations"),
                            (PERSONNEL, "Personnel"), (SUPPLY, "Supply")]:
            body = " ".join(rng.choices(pool, k=8))
            paras.append(f"## {label}\n\n{body}\n")
        sections = paras[1:]
        rng.shuffle(sections)
        note = paras[0] + "\n" + "\n".join(sections)
        if nid in inserts:
            parts = note.split("\n\n")
            pos = rng.randrange(2, len(parts))
            parts.insert(pos, inserts[nid])
            note = "\n\n".join(parts)
        combined = OPS + WEATHER + SUPPLY + PERSONNEL
        for j in range(3):
            filler = " ".join(rng.choices(combined, k=10))
            note += f"\n\n## Daily entries, part {j + 1}\n\n{filler}\n"
        (outdir / f"{nid}.md").write_text(note)
        total += len(note)
    (OUT / "README.md").write_text(
        "# Station logs archive\n\nSynthetic operations notes in notes/. "
        "Generated by gen_corpus3.py (deterministic).\n")
    print(f"wrote {N_NOTES} notes, {total} chars total")
    print("OVERRUN3  =", ",".join(overrun_ids))
    print("CORROSION3=", ",".join(corrosion_ids))
    print("WILDLIFE3 =", ",".join(wildlife_ids))


if __name__ == "__main__":
    build()
